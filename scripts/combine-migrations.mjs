// Joins supabase/migrations/*.sql, in order, into one file you can paste into the Supabase SQL editor:
//   npm run build:sql   ->   supabase/setup-all.sql   (generated; git-ignored so it can never go stale)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase');
const files = readdirSync(join(root, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `-- ===== ${f} =====\n${readFileSync(join(root, 'migrations', f), 'utf8').trim()}\n`).join('\n');
writeFileSync(join(root, 'setup-all.sql'), `-- Generated by scripts/combine-migrations.mjs. Run once on a NEW project.\n-- Do not run it twice: the migrations create tables and are not idempotent.\n\n${body}`);
console.log(`Wrote supabase/setup-all.sql from ${files.length} migrations:\n  ${files.join('\n  ')}`);
